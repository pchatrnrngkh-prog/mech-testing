/* ===== ตัวช่วยทั่วไป ===== */
const $ = (s, el = document) => el.querySelector(s);
const $$ = (s, el = document) => [...el.querySelectorAll(s)];
const fmt = (n, dp = 2) => Number(n).toLocaleString('en-US', { maximumFractionDigits: dp });
const sci = (n) => {
  const [m, e] = n.toExponential(3).split('e');
  return `${m} × 10<sup>${Number(e)}</sup>`;
};
const store = {
  get(k) { try { return localStorage.getItem(k); } catch { return null; } },
  set(k, v) { try { localStorage.setItem(k, v); } catch { /* ไม่เป็นไร */ } }
};

/* ===== โหมดสว่าง / มืด ===== */
(function theme() {
  const saved = store.get('theme');
  if (saved) document.documentElement.dataset.theme = saved;
  $('#themeBtn').addEventListener('click', () => {
    const dark = document.documentElement.dataset.theme
      ? document.documentElement.dataset.theme === 'dark'
      : matchMedia('(prefers-color-scheme: dark)').matches;
    const next = dark ? 'light' : 'dark';
    document.documentElement.dataset.theme = next;
    store.set('theme', next);
  });
})();

/* ===== เมนูไฮไลต์ตามตำแหน่ง + ปุ่มกลับด้านบน ===== */
(function nav() {
  const links = $$('#nav a');
  const secs = links.map(a => $(a.getAttribute('href')));
  const toTop = $('#toTop');
  const onScroll = () => {
    const y = scrollY + 120;
    let cur = -1;
    secs.forEach((s, i) => { if (s && s.offsetTop <= y) cur = i; });
    links.forEach((a, i) => a.classList.toggle('active', i === cur));
    if (cur >= 0) links[cur].scrollIntoView({ block: 'nearest', inline: 'nearest' });
    toTop.classList.toggle('show', scrollY > 600);
  };
  addEventListener('scroll', onScroll, { passive: true });
  toTop.addEventListener('click', () => scrollTo({ top: 0 }));
  onScroll();
})();

