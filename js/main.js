const CALCS = {
  tensile(v) {
    need(v, ['d', 'Fu', 'L0', 'Lu']);
    const A = Math.PI * v.d ** 2 / 4;
    const su = v.Fu * 1000 / A;
    const el = (v.Lu - v.L0) / v.L0 * 100;
    const out = [
      { k: 'พื้นที่หน้าตัด Sₒ', v: `${fmt(A)} mm²`, w: `π × ${v.d}² / 4` },
      { k: 'ความแข็งแรงดึงสูงสุด σᵤ', v: `${fmt(su)} MN/m²`, w: `${fmt(v.Fu * 1000)} N ÷ ${fmt(A)} mm²` },
      { k: 'เปอร์เซ็นต์ความยืด δₜ', v: `${fmt(el)} %`, w: `(${v.Lu} − ${v.L0}) ÷ ${v.L0} × 100` }
    ];
    if (v.Fp > 0 && v.dp > 0) {
      const s = v.Fp * 1000 / A, e = v.dp / v.L0, E = s / e;
      out.push(
        { k: 'ความเค้นที่ปลายช่วงเส้นตรง σ', v: `${fmt(s)} MN/m²`, w: `${fmt(v.Fp * 1000)} ÷ ${fmt(A)}` },
        { k: 'ความเครียด ε', v: fmt(e, 5), w: `${v.dp} ÷ ${v.L0}` },
        { k: 'มอดุลัสของความยืดหยุ่น E', v: `${fmt(E / 1000)} GN/m²`, w: `${fmt(s)} ÷ ${fmt(e, 5)} = ${fmt(E, 0)} MN/m²` }
      );
    }
    return out;
  },
  compression(v) {
    need(v, ['d', 'F', 'h0', 'hL']);
    const A = Math.PI * v.d ** 2 / 4;
    return [
      { k: 'พื้นที่หน้าตัด Sₒ', v: `${fmt(A)} mm²`, w: `π × ${v.d}² / 4` },
      { k: 'ความแข็งแรงอัดสูงสุด σ꜀', v: `${fmt(v.F * 1000 / A)} MN/m²`, w: `${fmt(v.F * 1000)} N ÷ ${fmt(A)} mm²` },
      { k: 'เปอร์เซ็นต์การยุบตัว ε꜀', v: `${fmt((v.h0 - v.hL) / v.h0 * 100)} %`, w: `(${v.h0} − ${v.hL}) ÷ ${v.h0} × 100` }
    ];
  },
  shear(v) {
    const round = v.shape === 'round';
    need(v, round ? ['a', 'F'] : ['a', 'b', 'F']);
    const A = round ? Math.PI * v.a ** 2 / 4 : v.a * v.b;
    const n = Number(v.mode);
    return [
      { k: 'พื้นที่หน้าตัด A', v: `${fmt(A)} mm²`, w: round ? `π × ${v.a}² / 4` : `${v.a} × ${v.b}` },
      { k: `ความแข็งแรงเฉือนสูงสุด τ (${n === 2 ? 'เฉือนคู่' : 'เฉือนเดี่ยว'})`, v: `${fmt(v.F * 1000 / (n * A))} MN/m²`,
        w: `${fmt(v.F * 1000)} N ÷ (${n === 2 ? '2 × ' : ''}${fmt(A)} mm²)` }
    ];
  },
  torsion(v) {
    need(v, ['kg', 'R', 'd']);
    const F = v.kg * 9.81, T = F * v.R;
    const dm = v.d / 1000, J = Math.PI * dm ** 4 / 32, tau = T * (dm / 2) / J;
    return [
      { k: 'แรง F', v: `${fmt(F)} N`, w: `${v.kg} × 9.81` },
      { k: 'โมเมนต์บิด T', v: `${fmt(T)} N·m`, w: `${fmt(F)} × ${v.R}` },
      { k: 'โมเมนต์เฉื่อยเชิงขั้ว J', v: `${sci(J)} m⁴`, w: `π × ${dm}⁴ / 32` },
      { k: 'ความเค้นเฉือนบิดสูงสุด τ', v: `${fmt(tau / 1e6)} MN/m²`, w: `${fmt(T)} × ${dm / 2} ÷ J` }
    ];
  },
  hardness(v) {
    if (v.type === 'HB') {
      need(v, ['kgf', 'D', 'd']);
      if (v.d >= v.D) throw new Error('ขนาดรอยกด d ต้องเล็กกว่าเส้นผ่าศูนย์กลางลูกบอล D');
      const HB = 2 * v.kgf / (Math.PI * v.D * (v.D - Math.sqrt(v.D ** 2 - v.d ** 2)));
      return [{ k: 'ความแข็งบริเนลล์', v: `${fmt(HB, 0)} HB`,
        w: `HB = 2F / [πD(D − √(D² − d²))] = 2(${v.kgf}) / [π(${v.D})(${v.D} − √(${v.D}² − ${v.d}²))]` }];
    }
    need(v, ['kgf', 'd']);
    const HV = 1.8544 * v.kgf / v.d ** 2;
    return [{ k: 'ความแข็งวิคเกอร์ส', v: `${fmt(HV, 0)} HV`, w: `HV = 1.8544 F / d² = 1.8544 × ${v.kgf} / ${v.d}²` }];
  }
};

function need(v, keys) {
  for (const k of keys) {
    if (!(v[k] > 0)) throw new Error('กรอกตัวเลขให้ครบ และต้องมากกว่า 0');
  }
}

$$('.calc[data-calc]').forEach(box => {
  const fn = CALCS[box.dataset.calc];
  const out = $('.calc-out', box);
  const run = () => {
    const v = {};
    $$('input, select', box).forEach(i => {
      v[i.name] = i.tagName === 'SELECT' ? i.value : (i.value === '' ? NaN : Number(i.value));
    });
    try {
      out.innerHTML = fn(v).map(r =>
        `<div class="res"><div class="k">${r.k}</div><div class="v">${r.v}</div><div class="w">${r.w}</div></div>`).join('');
    } catch (err) {
      out.innerHTML = `<div class="calc-err">⚠️ ${err.message}</div>`;
    }
  };
  box.addEventListener('input', run);
  box.addEventListener('change', run);
  run();
});

