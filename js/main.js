(function decoder() {
  const input = $('#decInput');
  const out = $('#decOut');
  const part = (v, k) => `<div class="part"><div class="pv">${v}</div><div class="pk">${k}</div></div>`;
  const RW = {
    A: 'หัวกดเพชรรูปกรวย', B: 'หัวกดลูกบอลเหล็กกล้า ⌀ 1/16 นิ้ว', C: 'หัวกดเพชรรูปกรวย มุม 120°'
  };
  const run = () => {
    const m = input.value.trim().match(/^([\d.]+)\s*(HB|HV|HR\s*([A-Z]))\s*(.*)$/i);
    if (!m) { out.innerHTML = '<div class="calc-err">⚠️ รูปแบบไม่ถูกต้อง ลองพิมพ์เช่น 170 HB 5/250/30</div>'; return; }
    const val = m[1], kind = m[2].toUpperCase().replace(/\s/g, ''), rest = m[4].split('/').map(s => s.trim()).filter(Boolean);
    let html = part(val, 'ค่าความแข็ง');
    if (kind === 'HB') {
      html += part('HB', 'ความแข็งแบบบริเนลล์');
      if (rest.length === 3) {
        html += part(`${rest[0]} mm`, 'ขนาด ⌀ ลูกบอลเหล็ก') + part(`${rest[1]} kg`, 'แรงกดทดสอบ') + part(`${rest[2]} s`, 'เวลากดแช่');
      } else {
        html += part('10 mm / 29,420 N / 10–15 s', 'ไม่มีตัวเลขตามหลัง = ใช้เกณฑ์มาตรฐาน');
      }
    } else if (kind === 'HV') {
      html += part('HV', 'ความแข็งแบบวิคเกอร์ส');
      if (rest.length >= 1) html += part(`${rest[0]} N`, 'แรงกดทดสอบ');
      if (rest.length >= 2) html += part(`${rest[1]} s`, 'เวลากดแช่');
      if (!rest.length) html += part('มาตรฐาน', 'ไม่มีตัวเลขตามหลัง = ใช้เกณฑ์มาตรฐาน');
    } else {
      const sc = m[3].toUpperCase();
      html += part(kind, `ความแข็งแบบรอคเวลล์ สเกล ${sc}`);
      if (RW[sc]) html += part(RW[sc], 'หัวกดที่ใช้');
      html += part('ความลึกรอยกด', 'สิ่งที่วัด');
    }
    out.innerHTML = html;
  };
  input.addEventListener('input', run);
  $$('#decoder [data-ex]').forEach(b => b.addEventListener('click', () => { input.value = b.dataset.ex; run(); }));
  run();
})();

