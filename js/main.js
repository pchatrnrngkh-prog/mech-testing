(function quiz() {
  const tabs = $('#quizTabs'), box = $('#quizBox'), scoreEl = $('#quizScore'), titleEl = $('#quizTitle');
  let cur = 0, right = 0, answered = 0;

  tabs.innerHTML = QUIZ.map((s, i) => `<button data-i="${i}">${i + 1}. ${s.title}</button>`).join('');
  tabs.addEventListener('click', e => { const b = e.target.closest('button'); if (b) load(+b.dataset.i); });
  $('#quizReset').addEventListener('click', () => load(cur));

  function load(i) {
    cur = i; right = 0; answered = 0;
    $$('button', tabs).forEach((b, j) => b.classList.toggle('on', j === i));
    const set = QUIZ[i];
    titleEl.textContent = set.title;
    box.innerHTML = set.qs.map((q, qi) => `
      <div class="q" data-q="${qi}">
        <div class="q-text"><span class="qn">${qi + 1}.</span>${q.q}</div>
        <div class="choices">${q.c.map((c, ci) => `<button data-c="${ci}">${c}</button>`).join('')}</div>
      </div>`).join('') + '<div id="quizResult"></div>';
    updateScore();
  }

  box.addEventListener('click', e => {
    const b = e.target.closest('.choices button');
    if (!b || b.disabled) return;
    const qEl = b.closest('.q'), q = QUIZ[cur].qs[+qEl.dataset.q], pick = +b.dataset.c;
    const ok = pick === q.a;
    $$('button', qEl).forEach((x, i) => {
      x.disabled = true;
      if (i === q.a) x.classList.add('correct');
      else if (i === pick) x.classList.add('wrong');
    });
    qEl.insertAdjacentHTML('beforeend', `<div class="explain ${ok ? 'ok' : 'no'}">${ok ? '🎉 ถูกต้อง!' : '❌ ยังไม่ถูก'} ${q.e}</div>`);
    answered++; if (ok) right++;
    updateScore();
  });

  function updateScore() {
    const n = QUIZ[cur].qs.length;
    scoreEl.textContent = `ถูก ${right} / ${n}`;
    const res = $('#quizResult');
    if (answered === n) {
      const pct = Math.round(right / n * 100);
      const msg = pct >= 80 ? 'ยอดเยี่ยม! เข้าใจเนื้อหาดีมาก 🏆' : pct >= 50 ? 'ดีแล้ว ลองทบทวนข้อที่ผิดอีกนิด 💪' : 'กลับไปทบทวนเนื้อหาแล้วลองใหม่นะ 📚';
      res.innerHTML = `<div class="result-box"><div class="big">${right} / ${n}</div><div>${msg}</div></div>`;
    } else if (res) res.innerHTML = '';
  }

  load(0);
})();
